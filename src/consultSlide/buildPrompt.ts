/** Shared prompt for consult slide Gemini extract (Apps Script duplicates this text). */
import type { ConsultSlideConsultContext, ConsultSlidePatientContext } from './types';

export function buildConsultSlideExtractPrompt(
  patient: ConsultSlidePatientContext,
  consult: ConsultSlideConsultContext
): string {
  return [
    'Bạn là trợ lý OCR phiếu hành chính + TTE nhi khoa Việt Nam.',
    'Trích xuất ĐÚNG chữ trên ảnh; không đoán bừa.',
    '',
    'Dữ liệu hệ thống (chỉ dùng khi ảnh mờ):',
    JSON.stringify({ patient, consult }, null, 2),
    '',
    'Quy tắc bắt buộc:',
    '- PatientName = tên BÉ/BỆNH NHI (dòng Họ và tên). KHÔNG lấy tên mẹ/bố/người nhà/BS chỉ định.',
    '- PatientID1 = Mã NB hoặc Mã BN (chữ số, thường 8–12 số).',
    '- PatientID2 = Mã HS nếu có; không thì "".',
    '- CẤM đưa vào PatientID1/2: mã TE…, barcode, QR, RIS, PID ký tự lạ.',
    '- PatientDOB bắt buộc nếu có trên phiếu (dd/mm/yyyy).',
    '- PatientPhone = SĐT trên phiếu.',
    '- PatientWeight/Height ưu tiên phiếu hành chính / chữ viết tay.',
    '- PatientAddress = địa chỉ NHÀ bệnh nhi (xã/huyện/tỉnh), KHÔNG lấy địa chỉ bệnh viện hay chữ “TP” trên tiêu đề BV.',
    '- Nếu suy ra được, PatientAddress ghi rõ tên tỉnh/TP ở cuối.',
    '- KHÔNG đưa RIS login, URL, QR credentials vào JSON.',
    '- tteFindings: bullet từng ý; tteConclusion tách riêng; DetailDiagnosis ưu tiên kết luận TTE.',
    '',
    'Trả về JSON thuần (không markdown) đúng schema:',
    '{',
    '  "PatientName": "",',
    '  "OtherPatientName": "",',
    '  "PatientID1": "",',
    '  "PatientID2": "",',
    '  "PatientSex": "",',
    '  "PatientDOB": "",',
    '  "PatientAddress": "",',
    '  "PatientPhone": "",',
    '  "PatientWeight": "",',
    '  "PatientHeight": "",',
    '  "ageLabel": "",',
    '  "clinicalSummary": "",',
    '  "DetailDiagnosis": "",',
    '  "historySummary": "",',
    '  "tteDate": "",',
    '  "tteFindings": [""],',
    '  "tteConclusion": "",',
    '  "ecgNote": "",',
    '  "cxrNote": "",',
    '  "surgNote": "",',
    '  "cathNote": ""',
    '}',
  ].join('\n');
}
